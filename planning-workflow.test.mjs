import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {draftFitsPlan,validDraft} from './backend/worker.js';
const P=createRequire(import.meta.url)('./placement-planner.js');
const coords=[[3,0],[3,-3],[0,-3],[-3,0],[-3,3],[0,3]].map(([q,r])=>({x:450+q+Math.floor(r/2),y:500+r}));
const plan=JSON.parse(readFileSync('placement-plan.json','utf8'));
const s=P.create(plan);P.clear(s,{includeLocked:true});P.clear(s,{zone:'grass',includeLocked:true});
const ids=[...s.players.values()].filter(p=>p.section==='Helm').slice(0,6).map(p=>p.id);
coords.forEach((p,i)=>s.assignments.set(ids[i],P.defineSite(s,p.x,p.y)));
s.sections.Helm={start:0,end:2*Math.PI,defencePacking:true};
assert(validDraft(P.exportDraft(s)));
assert(!draftFitsPlan(P.exportDraft(s),plan),'Final mode must reject internal openings');
assert.throws(()=>P.checkPlacement(s,ids[0],P.defineSite(s,430,500)),/enemy teleport opening/);
s.planningMode=true;
P.setSection(s,'Helm',0,360,{defencePacking:true});
assert(draftFitsPlan(P.exportDraft(s),plan),'Draft planning must allow saving zones with gaps');
const restored=P.create(plan);P.importDraft(restored,P.exportDraft(s));assert.equal(restored.planningMode,true);
P.checkPlacement(restored,ids[0],P.defineSite(restored,430,500));
assert.throws(()=>P.checkPlacement(restored,ids[0],P.defineSite(restored,coords[1].x+1,coords[1].y)),/action|close|occupied/i);
restored.locks.add(ids[0]);restored.locks.add(ids[1]);restored.pairs=[{strike:ids[0],reserve:ids[1]}];
P.clear(restored,{zone:'all',includeLocked:true});assert.equal(restored.locks.size,0);assert.deepEqual(restored.pairs,[]);assert([...restored.assignments.values()].every(v=>v===null));
assert(draftFitsPlan(P.exportDraft(restored),plan));
P.importDraft(restored,{...P.exportDraft(restored),planningMode:false});assert.equal(restored.planningMode,false);
assert(draftFitsPlan(P.exportDraft(restored),plan));
const bad=P.exportDraft(restored);bad.planningMode='yes';assert(!validDraft(bad));assert.throws(()=>P.importDraft(P.create(plan),bad),/planning/i);
console.log('Planning saves, persistence, gap bypass, collision checks and everyone-to-waiting passed');
